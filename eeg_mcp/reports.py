"""Builders for the standalone HTML views.

Split out from the MCP tool layer because two callers need them: the
``tools_viz`` tools, and the live monitor's Save buttons. Keeping them here
means the monitor does not have to import the tool module (which imports the
monitor), and the page each produces is identical however it was triggered.

Each builder takes a session and returns ``(path, summary)`` so the caller can
decide how to present the result.
"""

from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import numpy as np

from .config import get_config
from .dsp import band_powers, quality_metrics, welch_psd
from .utils import FREQ_BANDS
from .viz import (
    page,
    render_band_bars,
    render_psd,
    render_quality_table,
    render_traces,
    stat_tiles,
)


def plot_dir() -> Path:
    target = get_config().data_home / "plots"
    target.mkdir(parents=True, exist_ok=True)
    return target


def write_html(name: str, html: str) -> Path:
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    path = plot_dir() / f"{name}-{stamp}.html"
    path.write_text(html, encoding="utf-8")
    return path


def pick_channels(
    session: Any, data: np.ndarray, channels: list[str] | None
) -> tuple[np.ndarray, list[str]]:
    names = list(session.source.info.ch_names)
    if not channels:
        return data, names
    missing = [c for c in channels if c not in names]
    if missing:
        raise ValueError(f"Unknown channels {missing}. Available: {', '.join(names)}")
    idx = [names.index(c) for c in channels]
    return data[idx, :], list(channels)


def _stamp() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%SZ")


def build_traces(
    session: Any,
    seconds: float = 10.0,
    channels: list[str] | None = None,
    filtered: bool = True,
    show_events: bool = True,
) -> tuple[Path, dict[str, Any]]:
    """Traces snapshot with event markers."""
    data, timestamps, was_filtered = session.snapshot(seconds, filtered=filtered)
    data, names = pick_channels(session, data, channels)

    events = (
        [e.as_dict() for e in session.events.query(since=float(timestamps[0]), limit=80)]
        if show_events else []
    )
    info = session.source.info
    body = stat_tiles([
        ("Channels", str(len(names))),
        ("Sampling rate", f"{info.sfreq:g} Hz"),
        ("Window", f"{data.shape[1] / info.sfreq:.1f} s"),
        ("Signal", "filtered" if was_filtered else "raw"),
        ("Events shown", str(len(events))),
    ]) + "<div class='card'>" + render_traces(
        data, timestamps, names, events=events,
        title=f"{info.name} - {'filtered' if was_filtered else 'raw'}",
    ) + "</div>"

    path = write_html(f"traces-{session.session_id}", page(
        f"EEG traces - {session.session_id}",
        f"{info.kind} source '{info.name}' - {_stamp()}",
        body,
        "Generated by eeg-mcp. Amplitudes in microvolts; each channel is scaled "
        "to its own peak, shown at the right of its trace.",
    ))
    return path, {
        "path": str(path), "channels": names, "filtered": was_filtered,
        "n_samples": int(data.shape[1]), "n_events": len(events),
    }


def build_spectrum(
    session: Any,
    seconds: float = 8.0,
    channels: list[str] | None = None,
    filtered: bool = True,
    fmax: float = 60.0,
) -> tuple[Path, dict[str, Any]]:
    """PSD plus relative band composition."""
    data, _timestamps, was_filtered = session.snapshot(seconds, filtered=filtered)
    data, names = pick_channels(session, data, channels)
    info = session.source.info

    freqs, psd, backend = welch_psd(data, info.sfreq)
    mask = freqs <= fmax
    freqs, psd = freqs[mask], psd[:, mask]
    power = band_powers(data, info.sfreq, ch_names=names, relative=True)
    peaks = {n: float(freqs[int(np.argmax(psd[i]))]) for i, n in enumerate(names)}

    body = stat_tiles([
        ("Dominant band", power["dominant_band"]),
        ("Window", f"{data.shape[1] / info.sfreq:.1f} s"),
        ("Resolution", f"{(freqs[1] - freqs[0]):.2f} Hz" if freqs.size > 1 else "n/a"),
        ("Signal", "filtered" if was_filtered else "raw"),
    ])
    body += "<div class='card'>" + render_psd(
        freqs, psd, names, bands=dict(FREQ_BANDS)
    ) + "</div>"
    body += "<div class='card'>" + render_band_bars(
        power["per_channel"], list(FREQ_BANDS)
    ) + "</div>"
    body += ("<h2>Peak frequency</h2><div class='card'><table><thead><tr>"
             "<th>Channel</th><th>Peak (Hz)</th></tr></thead><tbody>")
    body += "".join(f"<tr><td>{n}</td><td>{v:.2f}</td></tr>" for n, v in peaks.items())
    body += "</tbody></table></div>"

    path = write_html(f"spectrum-{session.session_id}", page(
        f"Spectrum - {session.session_id}",
        f"{info.kind} source '{info.name}' - PSD backend: {backend}",
        body,
        "Generated by eeg-mcp. Power in dB relative to 1 uV^2/Hz.",
    ))
    return path, {
        "path": str(path), "peak_freq": peaks,
        "dominant_band": power["dominant_band"], "psd_backend": backend,
        "filtered": was_filtered,
    }


def build_report(
    session: Any,
    seconds: float = 10.0,
    include_spectrum: bool = True,
    notes: str | None = None,
) -> tuple[Path, dict[str, Any]]:
    """Full review page: traces, spectrum, quality, and the event log."""
    info = session.source.info
    data, timestamps, was_filtered = session.snapshot(seconds, filtered=True)
    raw_data, _ts, _f = session.snapshot(seconds, filtered=False)
    names = list(info.ch_names)

    quality = quality_metrics(raw_data, info.sfreq, ch_names=names)
    power = band_powers(data, info.sfreq, ch_names=names, relative=True)
    events = [e.as_dict() for e in session.events.query(limit=300)]
    status = session.status()

    body = ""
    if notes:
        body += f"<div class='card'><b>Notes.</b> {notes}</div>"
    body += stat_tiles([
        ("Source", info.name),
        ("Channels", str(info.n_channels)),
        ("Sampling rate", f"{info.sfreq:g} Hz"),
        ("Recorded", f"{status['buffered_sec']:.1f} s buffered"),
        ("Dominant band", power["dominant_band"]),
        ("Channels flagged", str(quality["n_bad"])),
        ("Events", str(len(events))),
        ("Filters", f"{status['filters']['n_stages']} stage(s)"),
    ])

    body += "<h2>Traces</h2><div class='card'>" + render_traces(
        data, timestamps, names,
        events=[e for e in events if e["timestamp"] >= float(timestamps[0])],
        title=f"{'filtered' if was_filtered else 'raw'} - last "
              f"{data.shape[1] / info.sfreq:.1f} s",
    ) + "</div>"

    if include_spectrum:
        freqs, psd, _backend = welch_psd(data, info.sfreq)
        mask = freqs <= 60.0
        body += "<h2>Spectrum</h2><div class='card'>" + render_psd(
            freqs[mask], psd[:, mask], names, bands=dict(FREQ_BANDS)
        ) + "</div>"
        body += "<div class='card'>" + render_band_bars(
            power["per_channel"], list(FREQ_BANDS)
        ) + "</div>"

    body += "<h2>Signal quality</h2><div class='card'>"
    body += render_quality_table(quality)
    if quality["bad_channels"]:
        body += (f"<p class='sub' style='margin-top:10px'>Attention: "
                 f"{', '.join(quality['bad_channels'])}</p>")
    body += "</div>"

    body += f"<h2>Events ({len(events)})</h2><div class='card'>"
    if events:
        body += ("<table><thead><tr><th>#</th><th>Time</th><th>Label</th>"
                 "<th>Origin</th><th>Value</th></tr></thead><tbody>")
        t0 = events[0]["timestamp"]
        for e in events[-120:]:
            body += (f"<tr><td>{e['event_id']}</td>"
                     f"<td>{e['timestamp'] - t0:+.3f}s</td>"
                     f"<td>{e['label']}</td><td>{e['origin']}</td>"
                     f"<td>{'' if e['value'] is None else e['value']}</td></tr>")
        body += "</tbody></table>"
    else:
        body += "<p class='empty'>No events recorded.</p>"
    body += "</div>"

    path = write_html(f"report-{session.session_id}", page(
        f"Session report - {session.session_id}",
        f"{info.kind} source '{info.name}' - {_stamp()}",
        body,
        "Generated by eeg-mcp for research use. Not a diagnostic device and not "
        "validated for clinical decision-making.",
    ))
    return path, {
        "path": str(path),
        "n_events": len(events),
        "bad_channels": quality["bad_channels"],
        "dominant_band": power["dominant_band"],
        "sections": ["traces"] + (["spectrum"] if include_spectrum else [])
                    + ["quality", "events"],
    }
